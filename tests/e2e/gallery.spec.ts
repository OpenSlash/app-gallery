import { expect, test } from '@playwright/test'

test('录入、调整尺寸、搜索、收藏、生命周期和刷新持久化', async ({ page }) => {
  const name = `测试应用 ${Date.now()}`
  await page.goto('/')
  await expect(page.getByRole('textbox', { name: '搜索应用' })).toBeVisible()
  await expect(page.locator('.intro')).toHaveCount(0)
  await expect(page.locator('.topbar')).toHaveText('app gallery.API Token')
  await expect(page.getByRole('button', { name: '显示全部应用' })).toHaveCount(0)
  await page.getByRole('button', { name: '添加应用', exact: true }).first().click()
  await page.getByLabel('应用名称').fill(name)
  await page.getByLabel('访问地址').fill('https://example.com')
  await page.getByLabel('一句话介绍').fill('浏览器端到端测试')
  await page.getByLabel('首次上线日期').fill('2026-01-01')
  await page.getByRole('combobox', { name: '卡片尺寸', exact: true }).click()
  await page.getByRole('option', { name: '大 · 2 × 2' }).click()
  await page.getByRole('button', { name: '添加应用', exact: true }).last().click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('textbox', { name: '搜索应用' }).fill(name)
  await expect(page.locator('.app-tile')).toHaveCount(1)
  await page.getByRole('button', { name: '卡片视图' }).click()
  await expect(page.locator('.app-tile')).toHaveClass(/size-large/)
  await expect(page.getByRole('link', { name: `访问 ${name}` })).toHaveAttribute('href', 'https://example.com')
  await page.getByRole('button', { name: `${name} 详情与尺寸` }).click()
  await expect(page.getByText('2026-01-01', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: '调整卡片尺寸' }).click()
  await page.getByRole('option', { name: '小 · 1 × 1' }).click()
  await expect(page.locator('.app-tile')).toHaveClass(/size-small/)
  await expect(page.getByLabel('调整卡片尺寸')).toBeEnabled()
  await page.getByRole('button', { name: '收藏', exact: true }).click()
  await expect(page.getByRole('button', { name: '已收藏', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  await expect(page.getByRole('button', { name: '恢复使用', exact: true })).toBeVisible()
  await page.getByLabel('补充说明').fill('恢复运行')
  await page.getByRole('button', { name: '恢复使用', exact: true }).click()
  await expect(page.getByRole('button', { name: '暂停', exact: true })).toBeVisible()
  await page.getByLabel('补充说明').fill('v0.1.0')
  await page.getByRole('button', { name: '记录发布', exact: true }).click()
  await expect(page.getByText('v0.1.0', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.reload()
  await page.getByRole('textbox', { name: '搜索应用' }).fill(name)
  await expect(page.locator('.app-tile')).toHaveCount(1)
  await expect(page.getByRole('link', { name: `打开收藏 ${name}` })).toBeVisible()
  await page.getByRole('button', { name: `${name} 详情与尺寸` }).click()
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByRole('combobox', { name: '卡片尺寸', exact: true }).click()
  await page.getByRole('option', { name: '中 · 2 × 1' }).click()
  await page.getByRole('button', { name: '保存更改' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(page.locator('.app-tile')).toHaveClass(/size-medium/)
  await page.getByRole('button', { name: `${name} 详情与尺寸` }).click()
  await page.getByRole('button', { name: '下线', exact: true }).click()
  await expect(page.getByRole('alertdialog')).toBeVisible()
  await expect(page.getByRole('alertdialog').getByRole('button', { name: '取消', exact: true })).toBeFocused()
  await page.getByRole('alertdialog').getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('alertdialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '下线', exact: true })).toBeFocused()
  await page.getByRole('button', { name: '下线', exact: true }).click()
  await page.getByRole('button', { name: '确认下线', exact: true }).click()
  await expect(page.getByRole('alertdialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '归档', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '归档', exact: true }).click()
  await page.getByRole('button', { name: '确认归档', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.app-tile')).toHaveCount(0)
})

test('移动端、自定义外观和键盘搜索', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript(() => {
    if (sessionStorage.getItem('preferences-test-initialized')) return
    localStorage.setItem('gallery-preferences', JSON.stringify({ wallpaper: 'sky', view: 'launchpad', scale: 104, showDays: true }))
    sessionStorage.setItem('preferences-test-initialized', 'true')
  })
  await page.goto('/')
  await expect(page.getByRole('textbox', { name: '搜索应用' })).toBeVisible()
  await expect(page.locator('.workspace')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(page.locator('.ambient')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '晴空', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '自定义' }).click()
  const slider = page.getByRole('slider', { name: '图标与卡片缩放' })
  await slider.focus()
  await slider.press('Home')
  for (let i = 0; i < 6; i++) await slider.press('ArrowRight')
  await expect(slider).toHaveAttribute('aria-valuenow', '128')
  await page.getByRole('checkbox', { name: '显示上线天数' }).uncheck()
  await page.reload()
  await expect(page.locator('.workspace')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await page.getByRole('button', { name: '自定义' }).click()
  await expect(page.getByRole('slider', { name: '图标与卡片缩放' })).toHaveAttribute('aria-valuenow', '128')
  await expect(page.getByRole('checkbox', { name: '显示上线天数' })).not.toBeChecked()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflow).toBe(false)
  await page.keyboard.press('Control+k')
  await expect(page.getByRole('textbox', { name: '搜索应用' })).toBeFocused()
})

test('Radix 组件键盘交互、图标选择与焦点恢复', async ({ page }) => {
  await page.goto('/')
  const add = page.getByRole('button', { name: '添加应用', exact: true }).first()
  await add.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toHaveAccessibleName('添加到我的空间')
  const type = page.getByRole('combobox', { name: '应用类型', exact: true })
  await type.focus()
  await type.press('Space')
  await expect(page.getByRole('listbox')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('listbox')).toHaveCount(0)
  await expect(dialog).toBeVisible()
  await expect(type).toBeFocused()
  await type.click()
  await page.getByRole('option', { name: '基础服务', exact: true }).click()
  await expect(type).toContainText('基础服务')
  const checkbox = page.getByRole('checkbox', { name: '收藏到 Dock' })
  await checkbox.focus()
  await checkbox.press('Space')
  await expect(checkbox).toBeChecked()
  await page.getByRole('button', { name: '图标：安全', exact: true }).click()
  await expect(page.getByRole('button', { name: '图标：安全', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '图标：音频', exact: true }).hover()
  await expect(page.getByRole('tooltip')).toContainText('音频')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(add).toBeFocused()
})
